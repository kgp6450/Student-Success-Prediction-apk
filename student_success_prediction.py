# Predictions
y_pred = model.predict(X_test)

# Evaluation metrics (as required)
mae = mean_absolute_error(y_test, y_pred)
r2 = r2_score(y_test, y_pred)

# Pass/Fail Accuracy (G3 >= 10 is considered "Pass" - common in this dataset)
pass_test = (y_test >= 10).astype(int)
pass_pred = (y_pred >= 10).astype(int)
acc = accuracy_score(pass_test, pass_pred)

print(" Model trained successfully!")
print(f"Mean Absolute Error (MAE): {mae:.2f}")
print(f"R-Squared (variance explained): {r2:.2f} ({r2*100:.1f}%)")
